Array = np.ndarray


def zero_mean_variance_derivative() -> float:
    """Return ``d Var[ReLU(N(0,v))] / dv``.

    ``E[ReLU(Z)^2]`` has derivative one half, but the closure transports a
    *central* covariance.  The derivative of the subtracted mean square is
    ``1/(2*pi)`` at zero mean.
    """

    return 0.5 - 1.0 / (2.0 * math.pi)


@dataclass(frozen=True)
class LocalKernels:
    """Local derivatives needed by the complete mean/covariance pullback.

    ``h_mu[i,j]`` and ``h_variance[i,j]`` are derivatives of output covariance
    entry ``V[i,j]`` with respect to input ``mu[i]`` and input variance
    ``C[i,i]`` respectively.  They are generated by central differences of
    the supplied full-covariance closure only for the small-width oracle.
    """

    probability: Array
    mean_variance_derivative: Array
    price_kernel: Array
    h_mu: Array
    h_variance: Array


@dataclass(frozen=True)
class CPLocalPullback:
    """A local CP update split before the free affine reset insertion."""

    mean_adjoint: Array
    scaled_u: Array
    inherited_g: Array
    reset_g: Array

    def factors_here(self) -> tuple[Array, Array]:
        """Return factors representing the covariance adjoint at this layer."""

        n = self.scaled_u.shape[0]
        return (
            np.concatenate((self.scaled_u, np.eye(n)), axis=1),
            np.concatenate((self.inherited_g, self.reset_g), axis=1),
        )


def _as_symmetric(matrix: Array) -> Array:
    matrix = np.asarray(matrix, dtype=np.float64)
    return 0.5 * (matrix + matrix.T)


def _minimum_safe_step(covariance: Array, requested: float) -> float:
    """Choose a symmetric diagonal finite-difference step inside the SPD cone."""

    eigen_minimum = float(np.min(np.linalg.eigvalsh(covariance)))
    if not np.isfinite(eigen_minimum) or eigen_minimum <= 1e-11:
        raise ValueError(
            "small-width Jacobian oracle requires a comfortably SPD covariance; "
            f"minimum eigenvalue was {eigen_minimum:.3e}"
        )
    return min(requested, 0.125 * eigen_minimum)


def local_kernels(
    mean: Array,
    covariance: Array,
    finite_difference_scale: float = 2e-5,
) -> LocalKernels:
    """Construct all local central-covariance kernels without a correction term.

    The Price matrix is analytic.  The two mean/covariance cross blocks are
    independently generated by central differences of the dense closure.  The
    method is intentionally slow and restricted to generated small widths;
    production cost claims must use analytic/AD derivatives instead.
    """

    mean = np.asarray(mean, dtype=np.float64)
    covariance = _as_symmetric(covariance)
    n = mean.size
    if covariance.shape != (n, n):
        raise ValueError("covariance shape must be (len(mean), len(mean))")

    variance = np.diag(covariance)
    if np.any(variance <= 0.0):
        raise ValueError("positive variance is required")
    sigma = np.sqrt(variance)
    alpha = mean / sigma
    probability = _normal_cdf(alpha)
    mean_variance_derivative = _normal_pdf(alpha) / (2.0 * sigma)

    correlation = np.clip(
        covariance / np.outer(sigma, sigma), -1.0 + 1e-12, 1.0 - 1e-12
    )
    price_kernel = phi2_gauss10(alpha[:, None], alpha[None, :], correlation)
    np.fill_diagonal(price_kernel, probability)
    price_kernel = _as_symmetric(price_kernel)

    h_mu = np.empty((n, n), dtype=np.float64)
    h_variance = np.empty((n, n), dtype=np.float64)
    identity = np.eye(n)
    for i in range(n):
        step_mu = finite_difference_scale * max(1.0, float(sigma[i]))
        _, covariance_plus = relu_gaussian_moments(mean + step_mu * identity[i], covariance)
        _, covariance_minus = relu_gaussian_moments(mean - step_mu * identity[i], covariance)
        h_mu[i] = (covariance_plus[i] - covariance_minus[i]) / (2.0 * step_mu)

        requested_variance_step = finite_difference_scale * max(float(variance[i]), 1e-8)
        step_variance = _minimum_safe_step(covariance, requested_variance_step)
        _, covariance_plus = relu_gaussian_moments(
            mean, covariance + step_variance * np.outer(identity[i], identity[i])
        )
        _, covariance_minus = relu_gaussian_moments(
            mean, covariance - step_variance * np.outer(identity[i], identity[i])
        )
        h_variance[i] = (
            covariance_plus[i] - covariance_minus[i]
        ) / (2.0 * step_variance)

    return LocalKernels(
        probability=probability,
        mean_variance_derivative=mean_variance_derivative,
        price_kernel=price_kernel,
        h_mu=h_mu,
        h_variance=h_variance,
    )


def _validate_adjoint_shapes(mean_adjoint: Array, covariance_adjoint: Array) -> tuple[Array, Array]:
    mean_adjoint = np.asarray(mean_adjoint, dtype=np.float64)
    covariance_adjoint = np.asarray(covariance_adjoint, dtype=np.float64)
    if mean_adjoint.ndim != 2:
        raise ValueError("mean_adjoint must have shape (width, outputs)")
    n, outputs = mean_adjoint.shape
    if covariance_adjoint.shape != (outputs, n, n):
        raise ValueError("covariance_adjoint must have shape (outputs, width, width)")
    return mean_adjoint, 0.5 * (covariance_adjoint + covariance_adjoint.swapaxes(1, 2))


def _cross_contractions(covariance_adjoint: Array, kernels: LocalKernels) -> tuple[Array, Array]:
    """Return the covariance-to-mean and covariance-to-variance blocks.

    In the symmetric Frobenius convention, the off-diagonal contribution occurs
    twice while a diagonal contribution occurs once:

    ``c_i = 2 sum_j A_ij H_ij - A_ii H_ii``.
    """

    diagonal_a = np.diagonal(covariance_adjoint, axis1=1, axis2=2).T

    def contract(h: Array) -> Array:
        paired = np.einsum("oij,ij->oi", covariance_adjoint, h, optimize=True).T
        return 2.0 * paired - diagonal_a * np.diag(h)[:, None]

    return contract(kernels.h_mu), contract(kernels.h_variance)


def dense_local_pullback(
    mean_adjoint: Array,
    covariance_adjoint: Array,
    kernels: LocalKernels,
    *,
    include_connected_price: bool,
) -> tuple[Array, Array]:
    """Dense reverse of one ReLU mean/central-covariance map.

    With ``include_connected_price=False`` this is the M120 base recurrence:
    off-diagonal Price factors are ``p_i p_j`` and the covariance diagonal is
    overwritten by the signed complete derivative.  With it true, the dense
    Price kernel is used and serves as the small-width finite-difference oracle.
    """

    mean_adjoint, covariance_adjoint = _validate_adjoint_shapes(
        mean_adjoint, covariance_adjoint
    )
    c_mu, c_variance = _cross_contractions(covariance_adjoint, kernels)
    mean_before = kernels.probability[:, None] * mean_adjoint + c_mu
    diagonal = (
        kernels.mean_variance_derivative[:, None] * mean_adjoint + c_variance
    )

    kernel = (
        kernels.price_kernel
        if include_connected_price
        else np.outer(kernels.probability, kernels.probability)
    )
    covariance_before = covariance_adjoint * kernel[None, :, :]
    indices = np.arange(mean_adjoint.shape[0])
    covariance_before[:, indices, indices] = diagonal.T
    return mean_before, covariance_before


def finite_difference_dense_pullback(
    mean: Array,
    covariance: Array,
    mean_adjoint: Array,
    covariance_adjoint: Array,
    finite_difference_scale: float = 2e-5,
) -> tuple[Array, Array]:
    """Independent dense central-difference oracle for one local pullback.

    Each output is differentiated simultaneously.  An off-diagonal covariance
    coordinate is perturbed as ``C_ij=C_ji += eps`` and its derivative is split
    equally between the two entries of the symmetric Frobenius adjoint.
    """

    mean = np.asarray(mean, dtype=np.float64)
    covariance = _as_symmetric(covariance)
    mean_adjoint, covariance_adjoint = _validate_adjoint_shapes(
        mean_adjoint, covariance_adjoint
    )
    n, outputs = mean_adjoint.shape
    if covariance.shape != (n, n) or mean.shape != (n,):
        raise ValueError("state shapes must match the adjoints")
    variance = np.diag(covariance)
    sigma = np.sqrt(variance)
    identity = np.eye(n)

    def objective(local_mean: Array, local_covariance: Array) -> Array:
        output_mean, output_covariance = relu_gaussian_moments(
            local_mean, local_covariance
        )
        return mean_adjoint.T @ output_mean + np.einsum(
            "oij,ij->o", covariance_adjoint, output_covariance, optimize=True
        )

    b_before = np.empty((n, outputs), dtype=np.float64)
    a_before = np.zeros((outputs, n, n), dtype=np.float64)
    for i in range(n):
        mean_step = finite_difference_scale * max(1.0, float(sigma[i]))
        derivative = (
            objective(mean + mean_step * identity[i], covariance)
            - objective(mean - mean_step * identity[i], covariance)
        ) / (2.0 * mean_step)
        b_before[i] = derivative

        requested_variance_step = finite_difference_scale * max(float(variance[i]), 1e-8)
        variance_step = _minimum_safe_step(covariance, requested_variance_step)
        perturbation = variance_step * np.outer(identity[i], identity[i])
        a_before[:, i, i] = (
            objective(mean, covariance + perturbation)
            - objective(mean, covariance - perturbation)
        ) / (2.0 * variance_step)

    for i in range(n):
        for j in range(i + 1, n):
            requested_covariance_step = finite_difference_scale * max(
                float(math.sqrt(variance[i] * variance[j])), 1e-8
            )
            covariance_step = _minimum_safe_step(covariance, requested_covariance_step)
            perturbation = covariance_step * (
                np.outer(identity[i], identity[j]) + np.outer(identity[j], identity[i])
            )
            coordinate_derivative = (
                objective(mean, covariance + perturbation)
                - objective(mean, covariance - perturbation)
            ) / (2.0 * covariance_step)
            a_before[:, i, j] = 0.5 * coordinate_derivative
            a_before[:, j, i] = 0.5 * coordinate_derivative
    return b_before, a_before


def cp_local_pullback(
    mean_adjoint: Array,
    u: Array,
    g: Array,
    kernels: LocalKernels,
) -> CPLocalPullback:
    """Shared-CP implementation of the corrected M120 base local recurrence.

    ``A[o] = U diag(G[o]) U.T``.  The returned reset is signed and is attached
    to identity columns only after all mean/covariance cross contractions have
    used the incoming representation.
    """

    mean_adjoint = np.asarray(mean_adjoint, dtype=np.float64)
    u = np.asarray(u, dtype=np.float64)
    g = np.asarray(g, dtype=np.float64)
    n, outputs = mean_adjoint.shape
    if u.ndim != 2 or u.shape[0] != n:
        raise ValueError("u must have shape (width, rank)")
    if g.shape != (outputs, u.shape[1]):
        raise ValueError("g must have shape (outputs, rank)")

    diagonal_a = (u * u) @ g.T

    def cp_contract(h: Array) -> Array:
        h_u = h @ u
        paired = (u * h_u) @ g.T
        return 2.0 * paired - diagonal_a * np.diag(h)[:, None]

    c_mu = cp_contract(kernels.h_mu)
    c_variance = cp_contract(kernels.h_variance)
    mean_before = kernels.probability[:, None] * mean_adjoint + c_mu
    diagonal = (
        kernels.mean_variance_derivative[:, None] * mean_adjoint + c_variance
    )
    scaled_u = kernels.probability[:, None] * u
    reset_g = (diagonal - (kernels.probability * kernels.probability)[:, None] * diagonal_a).T
    return CPLocalPullback(mean_before, scaled_u, g, reset_g)


def cp_affine_after_reset(
    weight: Array,
    local: CPLocalPullback,
) -> tuple[Array, Array, Array]:
    """Propagate CP factors through an affine map without a reset GEMM.

    The inherited factors require ``W @ (p*U)``.  The newly introduced identity
    reset atoms become the columns of ``W`` directly, which is why the cost
    ledger charges only the inherited rank.
    """

    weight = np.asarray(weight, dtype=np.float64)
    n = local.scaled_u.shape[0]
    if weight.shape != (n, n):
        raise ValueError("weight must be square and match the CP width")
    u_before = np.concatenate((weight @ local.scaled_u, weight), axis=1)
    g_before = np.concatenate((local.inherited_g, local.reset_g), axis=1)
    return weight @ local.mean_adjoint, u_before, g_before


def factors_to_dense(u: Array, g: Array) -> Array:
    """Materialize all output covariance adjoints from shared CP factors."""

    return np.einsum("ir,or,jr->oij", u, g, u, optimize=True)


def affine_dense_pullback(
    weight: Array,
    mean_adjoint: Array,
    covariance_adjoint: Array,
) -> tuple[Array, Array]:
    """Dense affine reverse under the input-output weight convention."""

    weight = np.asarray(weight, dtype=np.float64)
    mean_adjoint, covariance_adjoint = _validate_adjoint_shapes(
        mean_adjoint, covariance_adjoint
    )
    return (
        weight @ mean_adjoint,
        np.einsum("ia,oab,jb->oij", weight, covariance_adjoint, weight, optimize=True),
    )


def terminal_relu_adjoint(
    final_mean: Array,
    final_covariance: Array,
    final_weight: Array,
) -> tuple[Array, Array, Array]:
    """All-output adjoint of terminal ReLU means, factored as shared CP."""

    final_mean = np.asarray(final_mean, dtype=np.float64)
    final_covariance = _as_symmetric(final_covariance)
    final_weight = np.asarray(final_weight, dtype=np.float64)
    n, outputs = final_weight.shape
    if final_mean.shape != (outputs,) or final_covariance.shape != (outputs, outputs):
        raise ValueError("terminal shapes must agree with final_weight")
    variance = np.diag(final_covariance)
    sigma = np.sqrt(np.maximum(variance, 1e-14))
    alpha = final_mean / sigma
    probability = _normal_cdf(alpha)
    r = _normal_pdf(alpha) / (2.0 * sigma)
    return final_weight * probability[None, :], final_weight, np.diag(r)


def _relative(reference: Array, estimate: Array) -> tuple[float, float]:
    reference_norm = float(np.linalg.norm(reference))
    estimate_norm = float(np.linalg.norm(estimate))
    error = float(np.linalg.norm(reference - estimate))
    denominator = reference_norm * estimate_norm
    cosine = (
        1.0
        if denominator == 0.0 and error == 0.0
        else 0.0
        if denominator == 0.0
        else float(np.sum(reference * estimate)) / denominator
    )
    return error / max(reference_norm, 1e-300), cosine


def he_weights(seed: int, width: int, depth: int) -> tuple[Array, ...]:
    """Generated square He weights; ``depth`` includes the final affine map."""

    rng = np.random.default_rng(seed)
    return tuple(
        rng.normal(0.0, math.sqrt(2.0 / width), size=(width, width)).astype(np.float64)
        for _ in range(depth)
    )


def reverse_generated_network(
    weights: Sequence[Array],
    finite_difference_scale: float = 2e-5,
) -> dict[str, object]:
    """Compare complete CP-base and dense recurrences on generated weights.

    The result contains no correction, target, scorer, or terminal Born term.
    ``base`` omits the connected Price residual ``E``; ``exact`` retains it
    solely as a dense small-width Jacobian oracle.
    """

    raw = tuple(np.asarray(weight, dtype=np.float64) for weight in weights)
    layers, final_mean, final_covariance = build_gaussian_background(
        raw, relu_gaussian_moments
    )
    b_terminal, u_cp, g_cp = terminal_relu_adjoint(
        final_mean, final_covariance, raw[-1]
    )
    a_terminal = factors_to_dense(u_cp, g_cp)

    b_exact = b_terminal.copy()
    a_exact = a_terminal.copy()
    b_base = b_terminal.copy()
    a_base = a_terminal.copy()
    b_cp = b_terminal.copy()
    incoming_rank_ledger = [int(u_cp.shape[1])]
    rank_ledger = [int(u_cp.shape[1])]
    layer_metrics: list[dict[str, float | int]] = []

    for layer_index in range(len(layers) - 1, -1, -1):
        kernels = local_kernels(
            layers[layer_index].mean,
            layers[layer_index].covariance,
            finite_difference_scale,
        )
        b_exact, a_exact = dense_local_pullback(
            b_exact, a_exact, kernels, include_connected_price=True
        )
        b_base, a_base = dense_local_pullback(
            b_base, a_base, kernels, include_connected_price=False
        )
        cp_local = cp_local_pullback(b_cp, u_cp, g_cp, kernels)
        u_here, g_here = cp_local.factors_here()
        a_cp = factors_to_dense(u_here, g_here)
        cp_mean_relative, cp_mean_cosine = _relative(b_base, cp_local.mean_adjoint)
        cp_covariance_relative, cp_covariance_cosine = _relative(a_base, a_cp)
        base_exact_relative, base_exact_cosine = _relative(a_exact, a_base)
        layer_metrics.append(
            {
                "layer": layer_index,
                "incoming_rank": int(u_cp.shape[1]),
                "outgoing_rank": int(u_here.shape[1]),
                "cp_base_mean_relative": cp_mean_relative,
                "cp_base_mean_cosine": cp_mean_cosine,
                "cp_base_covariance_relative": cp_covariance_relative,
                "cp_base_covariance_cosine": cp_covariance_cosine,
                "base_exact_covariance_relative": base_exact_relative,
                "base_exact_covariance_cosine": base_exact_cosine,
            }
        )

        if layer_index > 0:
            b_exact, a_exact = affine_dense_pullback(raw[layer_index], b_exact, a_exact)
            b_base, a_base = affine_dense_pullback(raw[layer_index], b_base, a_base)
            b_cp, u_cp, g_cp = cp_affine_after_reset(raw[layer_index], cp_local)
            incoming_rank_ledger.append(int(u_cp.shape[1]))
            rank_ledger.append(int(u_cp.shape[1]))
        else:
            b_cp = cp_local.mean_adjoint
            u_cp, g_cp = u_here, g_here
            rank_ledger.append(int(u_cp.shape[1]))

    return {
        "base_mean": b_base,
        "base_covariance": a_base,
        "exact_mean": b_exact,
        "exact_covariance": a_exact,
        "cp_mean": b_cp,
        "cp_covariance": factors_to_dense(u_cp, g_cp),
        "incoming_rank_ledger": incoming_rank_ledger,
        "rank_ledger": rank_ledger,
        "layer_metrics": layer_metrics,
        "terminal_mean": relu_gaussian_moments(final_mean, final_covariance)[0],
    }


def matmul_cost(a: int, b: int, c: int) -> int:
    """The FlopScope dense-GEMM convention used by the M120 report."""

    return 2 * int(a) * int(b) * int(c) - int(a) * int(c)


def cost_ledger(
    width: int = 256,
    outputs: int = 256,
    hidden_relu_maps: int = 31,
    gaussian_background_flops: int = 6_189_000_000,
) -> dict[str, int | float]:
    """Independently recompute the mandatory all-output GEMM bill.

    The rank entering reverse ReLU map ``t`` is
    ``R_t=outputs+(t-1)*n``; this reduces to the report's ``R_t=t*n`` for
    ``outputs=n``.  Two cross blocks each charge ``L @ U`` plus
    ``(U*(L@U)) @ G.T``.  A reset introduces literal ``W`` columns, so affine
    CP propagation charges only the inherited rank.
    """

    n = int(width)
    o = int(outputs)
    h = int(hidden_relu_maps)
    if min(n, o, h) <= 0:
        raise ValueError("width, outputs, and hidden_relu_maps must be positive")
    incoming_ranks = tuple(o + (t - 1) * n for t in range(1, h + 1))
    diagonal = sum(matmul_cost(o, rank, n) for rank in incoming_ranks)
    one_cross_block = sum(
        matmul_cost(n, n, rank) + matmul_cost(n, rank, o)
        for rank in incoming_ranks
    )
    affine_u = sum(matmul_cost(n, n, rank) for rank in incoming_ranks[:-1])
    affine_mean = (h - 1) * matmul_cost(n, n, o)
    reverse = diagonal + 2 * one_cross_block + affine_u + affine_mean
    return {
        "variable_gemm_calls": h + 4 * h + 2 * (h - 1),
        "diagonal_flops": diagonal,
        "one_cross_block_flops": one_cross_block,
        "affine_u_flops": affine_u,
        "affine_mean_flops": affine_mean,
        "reverse_flops": reverse,
        "reverse_billions": reverse / 1e9,
        "with_background_flops": reverse + int(gaussian_background_flops),
        "with_background_billions": (reverse + int(gaussian_background_flops)) / 1e9,
    }
