"""Target-free reference for M120's corrected shared-CP Gaussian adjoint.

This is deliberately a *component* oracle.  It validates the reverse of the
full Gaussian ``(mean, central covariance)`` ReLU map but does not create a
weights-only correction source, combine a terminal Born diagram, or evaluate
any target-shaped efficacy metric.

The covariance adjoint is stored as symmetric dense matrices ``A[o, i, j]``
with the Frobenius pairing ``sum_ij A_ij dC_ij``.  Therefore an independent
off-diagonal covariance coordinate has a factor of two in the cross-block
contractions; keeping that convention explicit is what makes the signed
diagonal reset unambiguous.
"""

from __future__ import annotations

from dataclasses import dataclass
import math
from pathlib import Path
import sys
from typing import Sequence

import numpy as np


